CONCLUSIONS = r"""
================================================================================
阶段 0 结论：窗口操控可行性验证
================================================================================
环境：Windows / 三显示器 / 混合缩放 [100%, 125%, 150%] / Python 3.13.2

--------------------------------------------------------------------------------
结论 1：窗口枚举可行 ✅
--------------------------------------------------------------------------------
  实测：EnumWindows 枚举到 424 个顶层窗口，过滤后得到 16 个「真实可用」窗口。
  过滤规则（四条，缺一不可）：
    · IsWindowVisible == True
    · GetWindowTextLengthW > 0           （去掉无标题的隐形壳窗口）
    · 排除 WS_EX_TOOLWINDOW 且非 WS_EX_APPWINDOW
    · 排除几何为 (-32000,-32000) 且尺寸 160x28 的窗口 ← 这是最小化窗口的特征值
  实测过滤统计：不可见 390 / 无标题 15 / 工具窗口 3

  注意：最小化窗口的 GetWindowRect 返回 (-32000,-32000) 160x28，
        这是一个必须硬编码识别的哨兵值，否则预设里会存进垃圾坐标。


--------------------------------------------------------------------------------
结论 2：窗口指纹可辨识，但必须按优先级匹配 ✅⚠️
--------------------------------------------------------------------------------
  实测：16 个窗口中，8 个不同应用，其中 3 个应用存在多窗口。

    explorer.exe     4 个窗口，类名全部相同 (CabinetWClass)
                     → 只能靠标题区分
    msedge.exe       4 个窗口，类名全部相同 (Chrome_WidgetWin_1)
                     → 只能靠标题区分，但标题含「和另外 N 个页面」，会随标签页变化
    video-player.exe 3 个窗口，类名不同 (SubtitleWindowClass / Chrome_WidgetWin_1 x2)
                     → 两个 Chrome_WidgetWin_1 标题完全相同！无法靠标题区分

  ★ 关键结论：存在「同进程 + 同类名 + 同标题」的窗口对，
    单纯靠指纹无法唯一确定。必须引入 几何位置近似度 作为最后一级仲裁，
    并接受「可能匹配到孪生窗口」这一现实，在 UI 上让用户手动修正。


--------------------------------------------------------------------------------
结论 3：SetWindowPos 可用 ✅
--------------------------------------------------------------------------------
  实测：记事本窗口移动 → 位置 (1747,174) 变 (1807,234)，返回 True，err=0
        缩小测试 684x914 → 564x794 成功
        还原后矩形完全一致
  结论：普通权限下即可操控其他进程的窗口，无需提权（对本机这些目标而言）。


--------------------------------------------------------------------------------
结论 4：★★ 最重要的发现 —— 跨屏移动 + 改尺寸必须分两步 ★★
--------------------------------------------------------------------------------
  这是本次探针最有价值的产出，直接决定核心引擎的调用协议。

  实测数据（目标：文件资源管理器，三屏缩放 100% / 150% / 125%）：

    组1 同屏原地改尺寸        800x600  → 800x600   ✅ 精确
    组2 同屏内移动 + 改尺寸    800x600  → 800x600   ✅ 精确
    组3 跨屏移动 + 改尺寸      800x600  → 1200x900  ❌ 被乘了 1.5
                              800x600  → 667x500   ❌ 被乘了 0.8337
    组4 先跨屏移动，再单独改尺寸  750x550 → 750x550  ✅ 精确

  根因：
    在「同一次 SetWindowPos 调用」中同时改变窗口所属显示器与尺寸时，
    系统按【旧显示器】的 DPI 解释尺寸参数，窗口落到新屏后按【新 DPI】重算，
    产生乘性偏差：新尺寸 = 请求尺寸 × (新屏DPI / 旧屏DPI)。

  验证：
    150% / 100% = 1.5   → 800 × 1.5 = 1200  ✓ 吻合
    100% / 120% = 0.8333 → 800 × 0.8333 = 667 ✓ 吻合

  ★ 对策（核心引擎必须遵守）：
      还原一个跨屏窗口时，必须调用两次 SetWindowPos：
        第 1 次：只设位置（尺寸传当前实际尺寸，或先移动到目标屏）
        第 2 次：只设尺寸（位置传刚设好的位置）
      实测组4 证明这个两步法可以把误差完全消除。

  ★ 位置坐标不受影响：
      三组实验中「位置」永远精确命中，包括负坐标屏 (-1440,-834)。
      → 位置可以直接用物理像素存取，无需换算。


--------------------------------------------------------------------------------
结论 5：DPI 感知模式不改变上述行为 ⚠️
--------------------------------------------------------------------------------
  实测：unaware / system / pmv2 三种模式，组3 的缩放倍数完全一致。

  pmv2 模式下 SetProcessDpiAwarenessContext(-4) 返回 True，
  GetProcessDpiAwareness 从 0 变为 2，确实生效了。
  但跨屏缩放的偏差依然存在 —— 说明这个偏差与进程 DPI 感知无关，
  是窗口管理器的显示器迁移逻辑本身造成的。

  ★ 但 PMV2 仍然必须设置，理由不是修这个 bug，而是：
      · UNAWARE 下 GetMonitorInfo 返回的是「虚拟化后的逻辑坐标」，
        本机实测 150% 屏被报成 1707x1067 而不是真实的 2560x1600
      · PMV2 下才能拿到真实物理矩形 (23,-1600)-(2583,0) 与正确 dpi=144
      · 存储预设需要正确的物理尺寸，否则换显示配置后完全错乱


--------------------------------------------------------------------------------
结论 6：本机显示器实况（供存储模型设计参考）
--------------------------------------------------------------------------------
  [0] \\.\DISPLAY1  物理 (0,0)-(2560,1440)        100%  主屏
  [1] \\.\DISPLAY3  物理 (23,-1600)-(2583,0)      150%  纵向偏上，x 有 23 偏移
  [2] \\.\DISPLAY2  物理 (-1440,-834)-(0,1726)    125%  竖屏，负坐标

  ★ 三个显示器的原点各不相同，且含负坐标。
    → 预设不能只存绝对坐标，必须同时记录「所属显示器设备名 + 相对该屏工作区的偏移」。
    → 还原时先按设备名找屏，找不到再退回「按序号」或「按主屏」，
       并在 UI 上明确提示「显示器配置已变化」。


--------------------------------------------------------------------------------
结论 7：不适合纳入管理的窗口类型
--------------------------------------------------------------------------------
  · TkTopLevel (Tkinter 程序)：实测完全不响应 SetWindowPos 的尺寸参数，
    调用返回成功但窗口尺寸纹丝不动（在三个模式下都一样）。
    原因：Tk 自己在处理 Configure 事件时把尺寸改回去了。
    → 对策：此类窗口加入「尽力而为」类别，还原后校验，失败则提示用户。
  · UWP 窗口 (ApplicationFrameHost 托管，如记事本)：
    行为与普通窗口不同，实测三个 DPI 模式下表现完全一致，
    说明尺寸请求被 UWP 框架拦截。
  · 全屏独占窗口、反作弊保护的游戏窗口：不可控，直接跳过。
  · 常驻工具窗口（输入法、Overlay、Progman）：由过滤器排除。


--------------------------------------------------------------------------------
对后续开发的直接影响（设计约束清单）
--------------------------------------------------------------------------------
  [D1] 还原协议必须是「两次 SetWindowPos」：先位置，后尺寸。
  [D2] 程序启动最早期调用 SetProcessDpiAwarenessContext(-4)，
       早于任何窗口/控件创建。
  [D3] 存储模型：{显示器设备名, 相对工作区偏移, 物理尺寸} 三元组，而非绝对坐标。
  [D4] 匹配算法：进程名 → 类名 → 标题 → 几何近似度，四级仲裁；
       接受孪生窗口不可区分，提供 UI 手动指定。
  [D5] 最小化窗口的 (-32000,-32000) 哨兵值必须特判。
  [D6] 每次还原后必须回读 GetWindowRect 做校验，把「静默失败」变成明确提示。
  [D7] 无法保证成功的窗口类型（Tk/UWP/全屏）要在 UI 上标注，不承诺 100% 成功。
"""


